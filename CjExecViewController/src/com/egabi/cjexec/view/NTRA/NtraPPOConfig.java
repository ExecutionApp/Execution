package com.egabi.cjexec.view.NTRA;

public class NtraPPOConfig {
    private String ntraUrl;
    private String ntraUserName;
    private String ntraPassword;

    public void setNtraUrl(String ntraUrl) {
        this.ntraUrl = ntraUrl;
    }

    public String getNtraUrl() {
        return ntraUrl;
    }

    public void setNtraUserName(String ntraUserName) {
        this.ntraUserName = ntraUserName;
    }

    public String getNtraUserName() {
        return ntraUserName;
    }

    public void setNtraPassword(String ntraPassword) {
        this.ntraPassword = ntraPassword;
    }

    public String getNtraPassword() {
        return ntraPassword;
    }

}
